"""Post-hoc: the 1 km height-difference error of each DEM on peat cells only, at the four LiDAR sites.

    python script/peat_zone_rescore.py

Added 2026-11-05 after the Saleh-Sugihan benchmark (benchmark/dated_lidar.yaml, decision 2): that KHG holds mineral uplands
up to about 29 m in the south, where DeltaDTM (land below about 10 m) is not meant to work, while the other LiDAR sites are
nearly all peat. This rescoring is not one of the pre-set tests and is reported as such. Peat cells: peat thickness at least
50 cm in the KHG's 00_inputs/peat_depth.tif (cm), sampled at each LiDAR cell centre (nearest). Error maps are the step 02
outputs of script/dem_benchmark.py (candidate minus LiDAR on the LiDAR grid). The LiDAR's own 1 km height difference on the
same pairs is reported as the signal. Output: runs/checks/peat_zone_rescore.csv and .md.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import rasterio
import yaml
from rasterio.warp import Resampling, reproject

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(REPO.parent / "repeat-common" / "src"))
from canal_mask_sweep import pair_diffs  # noqa: E402
from dem_benchmark import out_dir  # noqa: E402
from repeat_common import khg  # noqa: E402

SITES = ["mendahara", "sugihan_lumpur", "saleh_sugihan", "pulau_padang"]
CANDIDATES = ["deltadtm__processed", "deltadtm", "klhk_modelled"]
MIN_PEAT_CM = 50
BASELINE_M = 1000


def read(path):
    with rasterio.open(path) as s:
        a = s.read(1).astype("float64")
        if s.nodata is not None:
            a[a == s.nodata] = np.nan
        return a, s


def main():
    import os
    data = Path(os.environ.get("REPEAT_DATA") or REPO.parent / "_data")
    rows = []
    for site in SITES:
        bc = yaml.safe_load(open(REPO / "benchmark" / f"{site}.yaml", encoding="utf-8"))
        bench, kdir = out_dir(bc), khg.folder(bc["khg"])
        em = bench / "02_error_maps"
        ref, rs = read(em / "deltadtm__processed_minus_lidar.tif")
        with rasterio.open(data / bc["lidar"]["path"]) as L:
            lid = np.full(ref.shape, np.nan)
            reproject(rasterio.band(L, 1), lid, dst_transform=rs.transform, dst_crs=rs.crs, resampling=Resampling.nearest,
                      src_nodata=L.nodata, dst_nodata=np.nan)
        lid[(lid < -100) | (lid > 1e4)] = np.nan
        with rasterio.open(kdir / "00_inputs" / "peat_depth.tif") as P:
            pd_ = np.full(ref.shape, np.nan)
            reproject(rasterio.band(P, 1), pd_, dst_transform=rs.transform, dst_crs=rs.crs, resampling=Resampling.nearest,
                      src_nodata=P.nodata, dst_nodata=np.nan)
        peat = np.isfinite(pd_) & (pd_ >= MIN_PEAT_CM)
        k = int(round(BASELINE_M / abs(rs.transform.a)))
        for zone, zm in (("all", np.ones_like(peat)), ("peat", peat), ("non-peat", ~peat)):
            for c in CANDIDATES:
                f = em / f"{c}_minus_lidar.tif"
                if not f.exists():
                    continue
                e, _ = read(f)
                ez = np.where(zm & np.isfinite(lid), e, np.nan)
                de, dl = pair_diffs(ez, np.where(np.isfinite(ez), lid, np.nan), k)
                rows.append({"site": site, "zone": zone, "candidate": c,
                             "cells_share": round(float(np.isfinite(ez).sum() / np.isfinite(np.where(np.isfinite(lid), e, np.nan)).sum()), 3),
                             "pairs": int(de.size), "rms_1km_m": round(float(np.sqrt(np.mean(de ** 2))), 3) if de.size else np.nan,
                             "lidar_signal_1km_m": round(float(np.sqrt(np.mean(dl ** 2))), 3) if dl.size else np.nan})
        print(site, "done", flush=True)
    R = pd.DataFrame(rows)
    R["ratio_to_signal"] = (R.rms_1km_m / R.lidar_signal_1km_m).round(2)
    dest = REPO / "runs" / "checks" / "peat_zone_rescore.csv"
    R.to_csv(dest, index=False)
    L = ["# 1 km height-difference error on peat cells only (post-hoc)", "",
         "Generated by `script/peat_zone_rescore.py`; do not edit. Not a pre-set test: added after the Saleh-Sugihan benchmark "
         f"because that KHG includes mineral uplands. Peat: thickness at least {MIN_PEAT_CM} cm in `00_inputs/peat_depth.tif`. "
         "Error of the 1 km height difference against the LiDAR (m) and the LiDAR's own 1 km height difference on the same pairs.", "",
         "| site | zone | candidate | share of cells | 1 km error (m) | LiDAR 1 km signal (m) | error / signal |", "|---|---|---|---|---|---|---|"]
    L += [f"| {r.site} | {r.zone} | {r.candidate} | {r.cells_share:.2f} | {r.rms_1km_m:.3f} | {r.lidar_signal_1km_m:.3f} | {r.ratio_to_signal:.2f} |"
          for _, r in R.iterrows()]
    dest.with_suffix(".md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(R.to_string(index=False))


if __name__ == "__main__":
    main()
