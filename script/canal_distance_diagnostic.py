"""Why is the smoothed DeltaDTM too high far from canals? Separate canopy bias from subsidence with ICESat-2.

    python script/canal_distance_diagnostic.py benchmark/canal_mask_sweep.yaml

The canal mask sweep (runs/checks/canal_mask_sweep.md) found DeltaDTM minus LiDAR rising with distance from the nearest
mapped canal. Two readings predict different things at the ICESat-2 ground points (2019-2025):
  - DeltaDTM keeps canopy in forest (away from canals): DeltaDTM - ICESat-2 rises with distance, ICESat-2 - LiDAR does not;
  - drained land subsided after the LiDAR flight (near canals): ICESat-2 - LiDAR falls toward canals as DeltaDTM - LiDAR does,
    and DeltaDTM - ICESat-2 stays flat.
At every usable step 04 ICESat-2 point (DeltaDTM run, datum-corrected height H) the script samples the LiDAR, the
DeltaDTM as delivered on the step 04 grid (column dem), the smoothed surface without mask at 300/150, and groups the
three differences by distance to the nearest mapped canal, WorldCover class, canopy height and business licence.
Each value is the group median minus the median over all points. Output: runs/checks/canal_distance_diagnostic.csv/.md.
"""
import argparse
import sys
from pathlib import Path

import geopandas as gpd
import numpy as np
import pandas as pd
import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
WS = REPO.parent
for p in (REPO, HERE, WS / "repeat-common" / "src"):
    sys.path.insert(0, str(p))
import os  # noqa: E402

from dem_benchmark import out_dir, sample  # noqa: E402
from repeat_common import khg  # noqa: E402

LC = {10: "tree cover", 20: "shrubland", 30: "grassland", 40: "cropland", 90: "herbaceous wetland", 95: "mangroves"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("config")
    a = ap.parse_args()
    cfg = yaml.safe_load(open(a.config, encoding="utf-8"))
    data = Path(os.environ.get("REPEAT_DATA") or WS / "_data")
    rows = []
    for sc in cfg["sites"]:
        bc = yaml.safe_load(open(REPO / sc, encoding="utf-8"))
        bench, kdir = out_dir(bc), khg.folder(bc["khg"])
        p = gpd.read_file(bench / "04_processed" / "deltadtm" / "ground_points.gpkg")
        p = p[p.split.isin(["calibration", "validation"])].copy()
        p["lidar"] = sample(str(data / bc["lidar"]["path"]), p.x.to_numpy(), p.y.to_numpy(), p.crs)
        p["smooth"] = sample(str(bench / cfg["out"] / "none_m300_g150.tif"), p.x.to_numpy(), p.y.to_numpy(), p.crs)
        can = gpd.read_file(kdir / cfg["canals"]).to_crs(p.crs)
        p["d_canal"] = gpd.sjoin_nearest(p[["geometry"]], can[["geometry"]], distance_col="d").groupby(level=0).d.min()
        lic = kdir / "00_inputs" / "national" / "izin_usaha_2025.gpkg"
        if lic.exists():
            L = gpd.read_file(lic).to_crs(p.crs)
            hit = gpd.sjoin(p[["geometry"]], L[["geometry"]], predicate="within").index
            p["licence"] = np.where(p.index.isin(hit), "inside licence", "outside licence")
        p = p[np.isfinite(p.lidar) & np.isfinite(p.dem) & np.isfinite(p.H)]
        diffs = {"icesat2_minus_lidar": p.H - p.lidar, "deltadtm_raw_minus_lidar": p.dem - p.lidar,
                 "deltadtm_raw_minus_icesat2": p.dem - p.H, "deltadtm_smooth_minus_lidar": p.smooth - p.lidar}
        meds = {k: float(np.nanmedian(v)) for k, v in diffs.items()}
        groups = {
            "distance to canal (m)": pd.cut(p.d_canal, [0, 50, 100, 250, 500, 1000, 2000, np.inf], right=False,
                                            labels=["0-50", "50-100", "100-250", "250-500", "500-1000", "1000-2000", ">2000"]),
            "WorldCover": p.lc.map(lambda v: LC.get(int(v), "other") if np.isfinite(v) else "none"),
            "canopy height (m)": pd.cut(p.chm.fillna(0), [-1, 2, 10, 20, 30, np.inf], labels=["<2", "2-10", "10-20", "20-30", ">30"]),
        }
        if "licence" in p:
            groups["licence"] = p.licence
        for gname, g in groups.items():
            for val, idx in p.groupby(g, observed=True).groups.items():
                r = {"site": bc["site"], "group": gname, "value": str(val), "n": len(idx)}
                for k, v in diffs.items():
                    r[k] = round(float(np.nanmedian(v.loc[idx])) - meds[k], 3)
                rows.append(r)
        rows.append({"site": bc["site"], "group": "overall median (m)", "value": "all", "n": len(p)} | {k: round(v, 3) for k, v in meds.items()})
        print(bc["site"], len(p), "points", flush=True)
    d = pd.DataFrame(rows)
    dest = REPO / "runs" / "checks" / "canal_distance_diagnostic.csv"
    d.to_csv(dest, index=False)
    cols = list(diffs)
    L = ["# DeltaDTM error against distance from canals: canopy or subsidence?", "",
         "Generated by `script/canal_distance_diagnostic.py`; do not edit. At step 04 ICESat-2 ground points (2019-2025). "
         "Group median minus the median over all points (m); the last row of each site gives the overall medians.", ""]
    for site in d.site.unique():
        L += [f"## {site}", "", "| group | value | n | " + " | ".join(c.replace("_", " ") for c in cols) + " |", "|---|---|---|" + "---|" * len(cols)]
        for _, r in d[d.site == site].iterrows():
            L.append(f"| {r.group} | {r.value} | {r.n} | " + " | ".join(f"{r[c]:+.3f}" for c in cols) + " |")
        L.append("")
    dest.with_suffix(".md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", dest.with_suffix(".md"))


if __name__ == "__main__":
    main()
